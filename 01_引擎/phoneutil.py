AREA_CODES = AREA_3 | AREA_4

RE_MOBILE = re.compile(r"^1[3-9]\d{9}$")
# 400 号码真实写法有 400-100-4520 / 400-1004-520 / 400-1697887 等多种分组，
# 但都是 400 + 7 位共 10 位，所以按位数判定，不去猜分隔符分组。
RE_400 = re.compile(r"^400\d{7}$")
# 座机必须带显式分隔符：区号 和 号码 之间要有 - 或空格。
# 否则 `02168888888`（021+8位）和噪音 `06513492989`（0651+7位）在
# 去掉分隔符后完全无法区分，只能靠"必须写分隔符"来消除歧义。
RE_LANDLINE = re.compile(r"^(0\d{2,3})[-\s—－–](\d{7,8})$")
# 无分隔符的裸串：只有"3 位区号 + 8 位"这一种可以安全判定。
# 依据：中国大陆只有 010-029 这批 3 位长途区号，且都是大区，
# 所以 0XX+8位 的切分是唯一的；而 4 位区号 + 7位 的裸串无法与
# 网页噪音区分（例如 06513492989 既像"西宁+7位"也像纯噪音），一律不认。
RE_LANDLINE_BARE = re.compile(r"^(0\d{2})(\d{8})$")


def normalize(raw: str) -> str:
    """轻量清洗：去首尾空白、全角空格，统一各种破折号。"""
    if not raw:
        return ""
    s = raw.strip()
    for ch in ("\u3000", "\xa0", " ", "\t", "\r", "\n"):
        s = s.replace(ch, "" if ch not in (" ",) else " ")
    for ch in ("\u2013", "\u2014", "\uff0d"):
        s = s.replace(ch, "-")
    return s.strip()


def classify(raw: str) -> str:
    """返回 'mobile' / 'landline' / 'service400' / '' (不合法)。"""
    s = normalize(raw)
    if not s:
        return ""

    if RE_400.match(re.sub(r"\D", "", s)):
        return "service400"

    digits = re.sub(r"\D", "", s)
    if digits.startswith("86") and len(digits) == 13:
        digits = digits[2:]
    if RE_MOBILE.match(digits):
        return "mobile"

    m = RE_LANDLINE.match(s)
    if m:
        area, sub = m.group(1), m.group(2)
        if area in AREA_CODES and not sub.startswith("0"):
            return "landline"
        return ""

    # 无分隔符的裸座机串：仅 010-029 这类 3 位区号 + 8 位可安全判定
    m_bare = RE_LANDLINE_BARE.match(digits)
    if m_bare and m_bare.group(1) in AREA_3 and not m_bare.group(2).startswith("0"):
        return "landline"

    return ""


def is_valid(raw: str) -> bool:
    return bool(classify(raw))
